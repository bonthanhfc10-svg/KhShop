export const getFeaturedProducts = (count = 8) =>
  products.filter((p) => p.isBestSeller).slice(0, count);

export const getNewArrivals = (count = 8) =>
  products.filter((p) => p.isNew).slice(0, count).length > 0
    ? products.filter((p) => p.isNew).slice(0, count)
    : products.slice(0, count);

export const getBestSellers = (count = 8) =>
  [...products].sort((a, b) => b.reviews - a.reviews).slice(0, count);

export const getSaleProducts = () => products.filter((p) => p.isSale);

export const getProductBySlug = (slug) =>
  products.find((p) => p.slug === slug);

export const getProductById = (id) => products.find((p) => p.id === Number(id));

export const getRelatedProducts = (product, count = 4) =>
  products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, count);

export const getProductsByCategory = (categorySlug) =>
  products.filter((p) => p.category === categorySlug);

export const searchProducts = (query) => {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.categoryName.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q)
  );
};

export const uniqueSizes = () => {
  const set = new Set();
  products.forEach((p) => p.sizes.forEach((s) => set.add(s)));
  return [...set];
};

export const uniqueBrands = () =>
  [...new Set(products.map((p) => p.brand))];

export const priceRange = () => {
  const prices = products.map((p) => p.price);
  return {
    min: Math.floor(Math.min(...prices)),
    max: Math.ceil(Math.max(...prices)),
  };
};

export const productColors = () => {
  const map = new Map();
  products.forEach((p) =>
    p.colors.forEach((c) => {
      if (!map.has(c.hex)) map.set(c.hex, c.name);
    })
  );
  return [...map.entries()].map(([hex, name]) => ({ name, hex }));
};

export default products;
